'use strict';
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('superSurferDesktop', {
  onWorkspaceCommand: callback => {const listener=(_,command)=>{if(['rearrange','sidebar','chat'].includes(command))callback(command);};ipcRenderer.on('workspace-command',listener);return ()=>ipcRenderer.removeListener('workspace-command',listener);},
  listPanels: () => ipcRenderer.invoke('panel:list'),
  onPanelClosed: callback => { const listener = (_, message) => callback(message); ipcRenderer.on('panel-closed', listener); return () => ipcRenderer.removeListener('panel-closed', listener); },
  openProviderLogin: backend => ipcRenderer.invoke('provider:login',backend),
  openPort: fields => ipcRenderer.invoke('port:open',fields),
  openPanel: fields => ipcRenderer.invoke('panel:open', fields),
  openRemoteProject: draft => ipcRenderer.invoke('project:remote', draft),
  takeProjectDraft: () => ipcRenderer.invoke('project:take-draft'),
  workspaceApi: (path,body) => ipcRenderer.invoke('workspace:api',path,body),
  uploadProjectFile: (projectId,name,uploadId,bytes) => ipcRenderer.invoke('workspace:upload',projectId,name,uploadId,bytes),
  loadProjectPdf: (projectId,path) => ipcRenderer.invoke('workspace:pdf',projectId,path),
  newWindow: () => ipcRenderer.invoke('window:new'),
  configuration: () => ipcRenderer.invoke('configuration'),
  connectionReady: () => ipcRenderer.invoke('connection:ready'),
  cancelConnection: () => ipcRenderer.invoke('connection:cancel'),
  connect: config => ipcRenderer.invoke('connect', config),
  listHosts: () => ipcRenderer.invoke('hosts:list'),
  listThemes: () => ipcRenderer.invoke('themes:list'),
  importTheme: () => ipcRenderer.invoke('themes:import'),
  getTheme: () => ipcRenderer.invoke('appearance:get'),
  setTheme: value => ipcRenderer.invoke('appearance:set', value),
  getWorkspace: () => ipcRenderer.invoke('workspace:get'),
  setWorkspace: value => ipcRenderer.invoke('workspace:set', value),
  getCustomizeStatus: () => ipcRenderer.invoke('customize:status'),
  chooseCustomizeSource: () => ipcRenderer.invoke('customize:source'),
  buildCustomize: projectId => ipcRenderer.invoke('customize:build',projectId),
  applyCustomize: () => ipcRenderer.invoke('customize:apply'),
  onStatus: callback => { const listener = (_, message) => callback(message); ipcRenderer.on('connection-status', listener); return () => ipcRenderer.removeListener('connection-status', listener); },
});
